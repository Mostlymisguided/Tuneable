const mongoose = require('mongoose');
const TuneBytesTransaction = require('../models/TuneBytesTransaction');

function mediaIdKey(id) {
  if (id == null || id === '') return null;
  if (typeof id === 'object') {
    // Mongoose ObjectId's `_id` getter returns the id itself. Recursing on it
    // overflows the stack while building the Global Party chart.
    if (id._id && id._id !== id) return mediaIdKey(id._id);
    if (typeof id.toString === 'function') {
      const key = id.toString();
      if (key && key !== '[object Object]') return key;
    }
    return null;
  }
  return String(id);
}

/**
 * Confirmed TuneBytes awarded on each media id.
 * This is the media total (every tipper), not one user's balance.
 */
async function sumConfirmedTuneBytesByMediaId(mediaIds) {
  const objectIds = [];
  const seen = new Set();
  for (const raw of mediaIds || []) {
    const key = mediaIdKey(raw);
    if (!key || seen.has(key) || !mongoose.Types.ObjectId.isValid(key)) continue;
    seen.add(key);
    objectIds.push(new mongoose.Types.ObjectId(key));
  }

  const totals = new Map();
  if (!objectIds.length) return totals;

  const rows = await TuneBytesTransaction.aggregate([
    { $match: { mediaId: { $in: objectIds }, status: 'confirmed' } },
    {
      $group: {
        _id: '$mediaId',
        totalTuneBytes: { $sum: '$tuneBytesEarned' },
      },
    },
  ]);

  for (const row of rows) {
    if (row._id) totals.set(row._id.toString(), row.totalTuneBytes || 0);
  }
  return totals;
}

function tuneBytesFor(totals, mediaId) {
  const key = mediaIdKey(mediaId);
  if (!key || !totals) return 0;
  return totals.get(key) || 0;
}

function nonNegativeTuneBytes(value) {
  const amount = Number(value);
  return Number.isFinite(amount) && amount > 0 ? amount : 0;
}

/**
 * Library cards always carry the TuneBytes a track generated.
 * The viewer's own earned amount is included only when they are looking
 * at their own library.
 */
function libraryTuneByteFields(mediaTotal, userEarned, { includeUserEarned = false } = {}) {
  const fields = { tuneBytesEarned: nonNegativeTuneBytes(mediaTotal) };
  if (!includeUserEarned) return fields;
  fields.userTuneBytesEarned = nonNegativeTuneBytes(userEarned);
  return fields;
}

function isVerifiedCreator(user) {
  return user?.creatorProfile?.verificationStatus === 'verified';
}

/**
 * Profile TuneBytes for a verified creator are the TuneBytes they earned
 * plus the TuneBytes generated by media they own. Everyone else shows only
 * what they earned. The stored user.tuneBytes balance is unchanged.
 */
function displayedProfileTuneBytes(user, ownedMediaTuneBytes) {
  const earned = Math.max(0, Number(user?.tuneBytes) || 0);
  if (!isVerifiedCreator(user)) return earned;
  return earned + Math.max(0, Number(ownedMediaTuneBytes) || 0);
}

/**
 * Confirmed TuneBytes generated by live media this user owns (percentage > 0).
 * A 0% mediaOwners row is a library-import placeholder, not ownership.
 */
async function sumTuneBytesGeneratedByOwnedMedia(userId) {
  const key = mediaIdKey(userId);
  if (!key || !mongoose.Types.ObjectId.isValid(key)) return 0;

  const Media = require('../models/Media');
  const ownerId = new mongoose.Types.ObjectId(key);
  const owned = await Media.find({
    status: { $nin: ['deleted', 'vetoed'] },
    mediaOwners: {
      $elemMatch: {
        userId: ownerId,
        percentage: { $gt: 0 },
      },
    },
  })
    .select('_id')
    .lean();

  if (!owned.length) return 0;
  const totals = await sumConfirmedTuneBytesByMediaId(owned.map((row) => row._id));
  let generated = 0;
  for (const value of totals.values()) {
    generated += Number(value) || 0;
  }
  return generated;
}

module.exports = {
  mediaIdKey,
  sumConfirmedTuneBytesByMediaId,
  tuneBytesFor,
  libraryTuneByteFields,
  isVerifiedCreator,
  displayedProfileTuneBytes,
  sumTuneBytesGeneratedByOwnedMedia,
};
