const mongoose = require('mongoose');
const { mediaIdKey, tuneBytesFor, displayedProfileTuneBytes, libraryTuneByteFields } = require('../utils/mediaTuneBytes');

describe('mediaTuneBytes', () => {
  it('reads a media total from object ids and nested ids', () => {
    const totals = new Map([['abc', 12.5]]);
    expect(tuneBytesFor(totals, 'abc')).toBe(12.5);
    expect(tuneBytesFor(totals, { _id: 'abc' })).toBe(12.5);
    expect(tuneBytesFor(totals, 'missing')).toBe(0);
    expect(tuneBytesFor(totals, null)).toBe(0);
  });

  it('stringifies object ids and ignores empty values', () => {
    expect(mediaIdKey('507f1f77bcf86cd799439011')).toBe('507f1f77bcf86cd799439011');
    expect(mediaIdKey({ _id: '507f1f77bcf86cd799439011' })).toBe('507f1f77bcf86cd799439011');
    const objectId = new mongoose.Types.ObjectId('507f1f77bcf86cd799439011');
    expect(mediaIdKey(objectId)).toBe('507f1f77bcf86cd799439011');
    expect(mediaIdKey({ _id: objectId })).toBe('507f1f77bcf86cd799439011');
    expect(mediaIdKey(null)).toBeNull();
    expect(mediaIdKey('')).toBeNull();
  });
});

describe('libraryTuneByteFields', () => {
  it('shares only the track total when the library belongs to someone else', () => {
    expect(libraryTuneByteFields(2365.2, 12.4)).toEqual({ tuneBytesEarned: 2365.2 });
    expect(libraryTuneByteFields(111, 0, { includeUserEarned: false })).toEqual({
      tuneBytesEarned: 111,
    });
  });

  it('includes what the viewer earned when the library is their own', () => {
    expect(libraryTuneByteFields(2365.2, 12.4, { includeUserEarned: true })).toEqual({
      tuneBytesEarned: 2365.2,
      userTuneBytesEarned: 12.4,
    });
    expect(libraryTuneByteFields(111, 0, { includeUserEarned: true })).toEqual({
      tuneBytesEarned: 111,
      userTuneBytesEarned: 0,
    });
  });
});

describe('displayedProfileTuneBytes', () => {
  const verified = {
    tuneBytes: 12.4,
    creatorProfile: { verificationStatus: 'verified' },
  };

  it('adds TuneBytes generated by owned media for a verified creator', () => {
    expect(displayedProfileTuneBytes(verified, 30)).toBeCloseTo(42.4);
  });

  it('shows only earned TuneBytes when the creator is not verified', () => {
    expect(displayedProfileTuneBytes({
      tuneBytes: 12.4,
      creatorProfile: { verificationStatus: 'pending' },
    }, 30)).toBeCloseTo(12.4);
    expect(displayedProfileTuneBytes({ tuneBytes: 8 }, 30)).toBe(8);
  });

  it('ignores a missing owned-media total', () => {
    expect(displayedProfileTuneBytes(verified, null)).toBeCloseTo(12.4);
    expect(displayedProfileTuneBytes({ creatorProfile: { verificationStatus: 'verified' } }, 5)).toBe(5);
  });
});
